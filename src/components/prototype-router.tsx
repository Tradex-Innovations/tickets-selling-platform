"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { Compass } from "lucide-react";
import { AccountScreen } from "@/screens/account/account-screen";
import { AdminDashboardScreen, AdminEventsScreen, AdminSellersScreen, AdminSettingsScreen } from "@/screens/admin/admin-screen";
import { CheckoutScreen } from "@/screens/booking/checkout-screen";
import { PaymentResultScreen } from "@/screens/booking/payment-result-screen";
import { SeatSelectionScreen } from "@/screens/booking/seat-selection-screen";
import { EventWizardScreen } from "@/screens/seller/event-wizard-screen";
import { MovieManagementScreen } from "@/screens/seller/movie-management-screen";
import { SellerDashboardScreen, SellerEventDetailScreen, SellerEventsScreen } from "@/screens/seller/seller-screen";
import { SellerOnboardingScreen } from "@/screens/seller/onboarding-screen";
import { HomeScreen } from "@/screens/marketplace/home-screen";
import { ExploreScreen } from "@/screens/marketplace/explore-screen";
import { EventDetailsScreen } from "@/screens/marketplace/event-details-screen";
import { DemoHubScreen, HelpScreen, OrganizerProfileScreen, VenueProfileScreen } from "@/screens/marketplace/profile-and-info-screens";
import { BoxOfficeSalesScreen, BoxOfficeScreen } from "@/screens/operations/box-office-screen";
import { CheckInScreen } from "@/screens/operations/check-in-screen";
import { GenericPortalScreen } from "@/screens/portals/generic-portal-screen";
import { LayoutBuilderScreen, LayoutsScreen, VenueCalendarScreen, VenueDashboardScreen } from "@/screens/venue/venue-screen";
import { Button, Card } from "@/components/ui/primitives";
import { normalizePathname } from "@/lib/pathname";

export function PrototypeRouter() {
  const pathname = normalizePathname(usePathname());
  const parts = pathname.split("/").filter(Boolean);
  if (pathname === "/") return <HomeScreen />;
  if (pathname === "/explore") return <ExploreScreen />;
  if (parts[0] === "events" && parts[1]) return <EventDetailsScreen eventId={parts[1]} />;
  if (parts[0] === "movies" && parts[1]) return <EventDetailsScreen eventId={parts[1]} movie />;
  if (parts[0] === "venues" && parts[1]) return <VenueProfileScreen venueId={parts[1]} />;
  if (parts[0] === "organizers" && parts[1]) return <OrganizerProfileScreen organizerId={parts[1]} />;
  if (parts[0] === "booking" && parts[1] && parts[2] === "seats") return <SeatSelectionScreen sessionId={parts[1]} />;
  if (pathname === "/checkout") return <CheckoutScreen />;
  if (pathname === "/payment/result") return <PaymentResultScreen />;
  if (pathname === "/help") return <HelpScreen />;
  if (pathname === "/legal/terms") return <HelpScreen legal="terms" />;
  if (pathname === "/legal/refunds") return <HelpScreen legal="refunds" />;
  if (pathname === "/demo") return <DemoHubScreen />;
  if (parts[0] === "account") return <AccountScreen section={parts[1] ?? "overview"} />;
  if (pathname === "/seller") return <SellerDashboardScreen />;
  if (pathname === "/seller/events") return <SellerEventsScreen />;
  if (pathname === "/seller/events/create") return <EventWizardScreen />;
  if (pathname === "/seller/onboarding") return <SellerOnboardingScreen />;
  if (pathname === "/seller/movies") return <MovieManagementScreen />;
  if (parts[0] === "seller" && parts[1] === "events" && parts[2]) return <SellerEventDetailScreen eventId={parts[2]} />;
  if (parts[0] === "seller" && parts[1]) return <GenericPortalScreen area="seller" section={parts[1]} />;
  if (pathname === "/venue-manager") return <VenueDashboardScreen />;
  if (pathname === "/venue-manager/calendar") return <VenueCalendarScreen />;
  if (pathname === "/venue-manager/layouts") return <LayoutsScreen />;
  if (pathname === "/venue-manager/layouts/builder") return <LayoutBuilderScreen />;
  if (parts[0] === "venue-manager" && parts[1]) return <GenericPortalScreen area="venue-manager" section={parts[1]} />;
  if (pathname === "/box-office") return <BoxOfficeScreen />;
  if (pathname === "/box-office/sales") return <BoxOfficeSalesScreen />;
  if (parts[0] === "box-office" && parts[1]) return <GenericPortalScreen area="box-office" section={parts[1]} />;
  if (pathname === "/check-in") return <CheckInScreen />;
  if (parts[0] === "check-in" && parts[1]) return <GenericPortalScreen area="check-in" section={parts[1]} />;
  if (pathname === "/admin") return <AdminDashboardScreen />;
  if (pathname === "/admin/events") return <AdminEventsScreen />;
  if (pathname === "/admin/sellers") return <AdminSellersScreen />;
  if (pathname === "/admin/settings") return <AdminSettingsScreen />;
  if (parts[0] === "admin" && parts[1]) return <GenericPortalScreen area="admin" section={parts[1]} />;
  return <div className="grid min-h-[75vh] place-items-center bg-[var(--surface)] p-5"><Card className="max-w-lg p-8 text-center"><span className="mx-auto grid size-14 place-items-center rounded-2xl bg-violet-50 text-[var(--brand)]"><Compass className="size-7" /></span><h1 className="mt-5 text-2xl font-bold">This route isn’t in the demo</h1><p className="mt-2 text-sm leading-6 text-[var(--muted)]">Use the marketplace or presentation hub to continue through a complete workflow.</p><div className="mt-6 flex justify-center gap-2"><Link href="/"><Button>Marketplace</Button></Link><Link href="/demo"><Button variant="outline">Demo hub</Button></Link></div></Card></div>;
}
